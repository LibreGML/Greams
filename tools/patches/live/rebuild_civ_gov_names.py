def all_civs() -> list[dict]:
    """主表 + 扩展表；同 tag 以主表为准。"""
    seen: set[str] = set()
    out: list[dict] = []
    for civ in CIVS + list(EXTRA_CIVS):
        t = civ["tag"]
        if t in seen:
            continue
        seen.add(t)
        out.append(civ)
    return out


def build_names() -> OrderedDict[str, str]:
    global GOV_TAGS
    GOV_TAGS = load_gov_tags()
    tags = list(GOV_TAGS.keys())
    out: OrderedDict[str, str] = OrderedDict()
    for civ in all_civs():
        for tag in tags:
            name = name_for(civ, tag)
            key = civ["tag"] if tag == "" else f"{civ['tag']}_{tag}"
            out[key] = name
    return out


def merge_bundle(new_names: OrderedDict[str, str]) -> tuple[int, int, int]:
    text = BUNDLE.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    existing: dict[str, str] = {}
    order: list[str] = []
    other_lines: list[str] = []  # non key=value preserved at top-ish

    kv_re = re.compile(r"^(\s*([^=\s][^=]*?)\s*=\s*)(.*?)(\s*)$")
    parsed: list[tuple[str, str, str, str] | None] = []
    for line in lines:
        raw = line.rstrip("\r\n")
        if not raw.strip() or raw.lstrip().startswith("#") or "=" not in raw:
            parsed.append(None)
            other_lines.append(line)
            continue
        k, v = raw.split("=", 1)
        key = k.strip()
        existing[key] = v.strip()
        order.append(key)
        parsed.append(("kv", key, k[: len(k) - len(k.lstrip())] if False else key, v))

    # Simpler approach: rebuild file as OrderedDict of all keys
    all_keys = OrderedDict()
    for line in lines:
        raw = line.rstrip("\r\n")
        if not raw.strip() or raw.lstrip().startswith("#") or "=" not in raw:
            continue
        k, v = raw.split("=", 1)
        all_keys[k.strip()] = v.strip()

    added = updated = same = 0
    for key, name in new_names.items():
        if key not in all_keys:
            all_keys[key] = name
            added += 1
        elif all_keys[key] != name:
            all_keys[key] = name
            updated += 1
        else:
            same += 1

    # Write: keep original order for old keys; append new keys at end in civ order
    out_lines: list[str] = []
    seen = set()
    for line in lines:
        raw = line.rstrip("\r\n")
        if not raw.strip() or raw.lstrip().startswith("#") or "=" not in raw:
            out_lines.append(raw)
            continue
        k, _ = raw.split("=", 1)
        key = k.strip()
        seen.add(key)
        out_lines.append(f"{key} = {all_keys[key]}")

    for key, name in new_names.items():
        if key not in seen:
            out_lines.append(f"{key} = {name}")
            seen.add(key)

    BUNDLE.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return added, updated, same


def export_docs(new_names: OrderedDict[str, str]) -> None:
    civ_list = all_civs()
    md = [
        "# 文明政体显示名（自动生成）",
        "",
        f"由 `tools/rebuild_civ_gov_names.py` 生成；覆盖 {len(civ_list)} 个文明 × {len(GOV_TAGS)} 政体。",
        "",
    ]
    rows = []
    for civ in civ_list:
        tag = civ["tag"]
        md.append(f"## {tag} — {new_names.get(tag, civ['short'])}")
        md.append("")
        md.append("| Extra_Tag | 政体 | 显示名 |")
        md.append("|---|---|---|")
        for extra, gov in GOV_TAGS.items():
            key = tag if extra == "" else f"{tag}_{extra}"
            disp = new_names[key]
            et = "(空)" if extra == "" else extra
            md.append(f"| `{et}` | {gov} | {disp} |")
            rows.append((tag, extra, gov, disp))
        md.append("")
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    import csv

    with OUT_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["civ_tag", "extra_tag", "government", "display_name"])
        w.writerows(rows)


def main() -> None:
    if not BACKUP.exists():
        shutil.copy2(BUNDLE, BACKUP)
        print(f"backup -> {BACKUP}")
    else:
        print(f"backup exists: {BACKUP}")

    civ_list = all_civs()
    names = build_names()
    print(f"generated {len(names)} names for {len(civ_list)} civs × {len(GOV_TAGS)} govs")
    added, updated, same = merge_bundle(names)
    print(f"bundle merge: added={added} updated={updated} unchanged={same}")
    export_docs(names)
