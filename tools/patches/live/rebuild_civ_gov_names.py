# Extra_Tag → 政体名（与 Governments.json 同步；脚本启动时再校验）
GOV_TAGS: OrderedDict[str, str] = OrderedDict()


def load_gov_tags() -> OrderedDict[str, str]:
    text = GOV.read_text(encoding="utf-8")
    names = re.findall(r'Name:\s*"([^"]*)"', text)
    extras = re.findall(r'Extra_Tag:\s*"([^"]*)"', text)
    return OrderedDict(zip(extras, names))


def tpl_republic(c: dict) -> str:
    return c.get("republic") or f"{c['short']}共和国"


def tpl_kingdom(c: dict) -> str:
    return c.get("kingdom") or f"{c['short']}王国"


def tpl_empire(c: dict) -> str:
    return c.get("empire") or f"{c['short']}帝国"


def name_for(c: dict, tag: str) -> str:
    """生成某文明在某 Extra_Tag 下的显示名。"""
    ov = c.get("overrides") or {}
    if tag in ov:
        return ov[tag]

    s = c["short"]
    muslim = c.get("muslim", False)
    arab = c.get("arab", False)

    if tag == "m":
        if c.get("feudal"):
            return c["feudal"]
        if c.get("prefer_empire_feudal"):
            return tpl_empire(c)
        return tpl_kingdom(c)

    table = {
        "": tpl_republic(c),
        "稻": tpl_republic(c),
        "进": tpl_republic(c),
        "r": c.get("federation") or f"{s}联邦共和国",
        "盖": c.get("consensus") or f"{s}联邦",
        "1": tpl_kingdom(c),
        "ys": c.get("dual_monarchy") or tpl_kingdom(c),
        "bgd": c.get("absolute") or tpl_kingdom(c),
        "三": c.get("enlightened") or tpl_kingdom(c),
        "秦": tpl_empire(c),
        "神": c.get("theocracy") or f"{s}神权国",
        "专": c.get("caliphate") or (f"{s}哈里发国" if muslim else f"{s}神权帝国"),
        "保": f"{s}贵族共和国",
        "cc": f"{s}寡头共和国",
        "(": f"{s}商业共和国",
        "s": f"{s}城邦",
        "t": f"{s}部落联盟",
        "h": c.get("khanate") or f"{s}汗国",
        "zh": c.get("principality") or f"{s}公国",
        "c": c.get("ml") or f"{s}人民共和国",
        "马": f"{s}人民民主共和国",
        "工": c.get("workers") or f"{s}社会主义自治共和国",
        "f": c.get("fascist") or f"{s}国",
        "长": c.get("totalitarian") or f"{s}国",
        "dc": c.get("authoritarian") or f"{s}共和国",
        "家": c.get("sultanate") or f"{s}苏丹国",
        "fu": c.get("hegemonic") or f"{s}共和国",
        "gt": f"{s}法团国家",
        "军": f"{s}军政府",
        "J": c.get("gunbu") or f"{s}军部政权",
        "毛": c.get("personalist") or f"{s}国",
        "企": c.get("developmental") or tpl_republic(c),
        "训": c.get("tutelage") or f"{s}国民政府",
        "凯": c.get("kemalist") or tpl_republic(c),
        "G": f"{s}国民公会共和国",
        "殖": f"{s}殖民地",
        "自": f"{s}自治领",
        "临": f"{s}临时政府",
        "jf": f"{s}军阀政权",
        "u": f"{s}叛乱政权",
        "C": f"{s}委员会共和国",
        "na": c.get("arab_soc") or (f"{s}阿拉伯共和国" if arab else f"{s}社会主义共和国"),
        "人": f"{s}过渡政府",
        "社": c.get("cabinet") or tpl_kingdom(c),
        "ac": c.get("theo_monarchy") or f"{s}政教王国",
    }
    return table[tag]


